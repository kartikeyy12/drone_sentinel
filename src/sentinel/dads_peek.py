"""Summarise DADS parquet shards without decoding audio to arrays.

DADS is stored as parquet shards with columns `audio` (struct: bytes, path) and `label` (0/1).
This module reports what is actually inside a few shards (row order, audio.path values, durations,
sample rates) so grouping and windowing decisions are made from data, not assumptions.
"""
from __future__ import annotations

import io
import logging
import math
from collections import Counter
from pathlib import Path
from typing import Any

import numpy as np
import pyarrow.parquet as pq
import soundfile as sf

log = logging.getLogger(__name__)
BEGIN, END = "<!-- DADS:BEGIN (generated by scripts/peek_dads_shards.py) -->", "<!-- DADS:END -->"


def summarize_shard(path: Path, batch_size: int = 1000) -> dict[str, Any]:
    """Summarise one shard: schema, labels, audio.path, durations, sample rates, row ordering."""
    pf = pq.ParquetFile(path)
    labels: list[int] = []
    paths: list[str | None] = []
    durs: list[float] = []
    srs: Counter[int] = Counter()
    errors = 0
    for batch in pf.iter_batches(batch_size=batch_size, columns=["audio", "label"]):
        for a, lab in zip(batch.column("audio").to_pylist(), batch.column("label").to_pylist()):
            labels.append(int(lab))
            paths.append(a.get("path") if a else None)
            try:
                info = sf.info(io.BytesIO(a["bytes"]))
                durs.append(float(info.duration))
                srs[int(info.samplerate)] += 1
            except Exception:  # noqa: BLE001
                errors += 1
                durs.append(math.nan)
    lab = np.array(labels)
    d = np.array(durs)
    stats: dict[str, Any] = {}
    for v in sorted(set(labels)):
        x = d[(lab == v) & ~np.isnan(d)]
        if len(x):
            stats[str(v)] = {"n": int(len(x)), "min": round(float(x.min()), 3),
                             "median": round(float(np.median(x)), 3), "mean": round(float(x.mean()), 3),
                             "max": round(float(x.max()), 3), "frac_shorter_than_1s": round(float((x < 1.0).mean()), 3)}
    present = [p for p in paths if p]
    n = len(paths)
    mid = n // 2
    return {
        "file": path.name, "rows": n, "schema": str(pf.schema_arrow).replace("\n", "; "),
        "label_counts": {str(k): int(v) for k, v in sorted(Counter(labels).items())},
        "label_runs_in_row_order": 1 + sum(labels[i] != labels[i - 1] for i in range(1, n)) if n else 0,
        "audio_path_non_empty": len(present), "audio_path_unique": len(set(present)),
        "audio_path_examples": {"first": paths[:6], "middle": paths[mid:mid + 4], "last": paths[-4:]},
        "sample_rates": {str(k): v for k, v in srs.items()}, "decode_errors": errors,
        "duration_s_by_label": stats,
    }


def render_markdown(summaries: list[dict[str, Any]]) -> str:
    """Markdown block for docs/data_notes.md."""
    out = [f"{BEGIN}", "", "Peek at a few DADS shards (scripts/peek_dads_shards.py). Full numbers: results/results.json, key `dads_peek`.", ""]
    for s in summaries:
        out += [f"### {s['file']}", f"- rows: {s['rows']}, labels: {s['label_counts']}, label runs in row order: {s['label_runs_in_row_order']}",
                f"- audio.path non-empty: {s['audio_path_non_empty']}, unique: {s['audio_path_unique']}",
                f"- audio.path examples: {s['audio_path_examples']}",
                f"- sample rates: {s['sample_rates']}, decode errors: {s['decode_errors']}",
                f"- duration (s) by label: {s['duration_s_by_label']}", ""]
    out.append(END)
    return "\n".join(out)


def replace_block(text: str, block: str) -> str:
    """Replace the generated DADS block in `text` (or append it)."""
    for b in (BEGIN, "<!-- DADS:BEGIN (generated by scripts/inspect_dads.py) -->"):
        if b in text and END in text:
            return text[: text.index(b)] + block + text[text.index(END) + len(END):]
    return text + "\n" + block + "\n"
