"""summarize_shard on a synthetic parquet shaped like DADS (audio struct + label)."""
from __future__ import annotations

import io

import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq
import soundfile as sf

from sentinel.dads_peek import BEGIN, END, render_markdown, replace_block, summarize_shard


def _wav_bytes(dur: float, sr: int = 16000) -> bytes:
    buf = io.BytesIO()
    sf.write(buf, np.zeros(int(dur * sr), dtype=np.float32), sr, format="WAV", subtype="PCM_16")
    return buf.getvalue()


def _shard(tmp_path, rows):
    audio = pa.array([{"bytes": b, "path": p} for b, p, _ in rows],
                     type=pa.struct([("bytes", pa.binary()), ("path", pa.string())]))
    table = pa.table({"audio": audio, "label": pa.array([l for _, _, l in rows], type=pa.int64())})
    path = tmp_path / "train-00000-of-00001.parquet"
    pq.write_table(table, path)
    return path


def test_summarize_shard(tmp_path):
    rows = [(_wav_bytes(0.5), "a_000.wav", 1), (_wav_bytes(0.5), "a_001.wav", 1),
            (_wav_bytes(2.0), "b_000.wav", 0), (_wav_bytes(1.0), None, 1)]
    s = summarize_shard(_shard(tmp_path, rows))
    assert s["rows"] == 4 and s["label_counts"] == {"0": 1, "1": 3}
    assert s["label_runs_in_row_order"] == 3
    assert s["audio_path_non_empty"] == 3 and s["audio_path_unique"] == 3
    assert s["sample_rates"] == {"16000": 4} and s["decode_errors"] == 0
    assert s["duration_s_by_label"]["1"]["frac_shorter_than_1s"] == round(2 / 3, 3)
    assert s["duration_s_by_label"]["0"]["median"] == 2.0


def test_decode_error_counted(tmp_path):
    s = summarize_shard(_shard(tmp_path, [(b"not a wav", "x.wav", 0), (_wav_bytes(1.0), "y.wav", 0)]))
    assert s["decode_errors"] == 1 and s["rows"] == 2


def test_replace_block_roundtrip(tmp_path):
    s = summarize_shard(_shard(tmp_path, [(_wav_bytes(1.0), "a.wav", 0)]))
    block = render_markdown([s])
    text = replace_block("intro\n<!-- DADS:BEGIN (generated by scripts/inspect_dads.py) -->\nold\n<!-- DADS:END -->\nouter", block)
    assert text.startswith("intro\n") and text.endswith("\nouter") and BEGIN in text and "old" not in text
    assert replace_block(text, block).count(END) == 1
