#!/usr/bin/env python
"""Inspect the downloaded DADS folder and write what is found into docs/data_notes.md.

Reports: directory tree (depth-limited), extension counts, total size, sample rate/duration of a
sample of audio files, parquet schemas (audio may be stored inside parquet), and the head of any
README / metadata files. Nothing about the layout is assumed.
"""
from __future__ import annotations

import argparse
import collections
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from sentinel.config import PROJECT_ROOT, load_config, project_path, set_seeds  # noqa: E402

BEGIN, END = "<!-- DADS:BEGIN (generated by scripts/inspect_dads.py) -->", "<!-- DADS:END -->"
AUDIO_EXT = {".wav", ".flac", ".mp3", ".ogg", ".m4a"}


def tree(root: Path, depth: int) -> list[str]:
    """Directory listing with file counts per directory, down to `depth`."""
    lines: list[str] = []
    for d in sorted([root] + [p for p in root.rglob("*") if p.is_dir() and ".cache" not in p.parts]):
        rel = d.relative_to(root)
        if len(rel.parts) > depth:
            continue
        n_files = sum(1 for p in d.iterdir() if p.is_file())
        lines.append(f"{'  ' * len(rel.parts)}{rel.name or '.'}/  ({n_files} files directly inside)")
    return lines


def inspect(root: Path, n_sample: int) -> str:
    """Build the markdown block describing the DADS folder."""
    import soundfile as sf

    files = [p for p in root.rglob("*") if p.is_file() and ".cache" not in p.parts]
    ext = collections.Counter(p.suffix.lower() for p in files)
    total = sum(p.stat().st_size for p in files)
    out = [f"Scanned `{root}`: {len(files)} files, {total / 1e9:.2f} GB.", "", "Extensions: " +
           ", ".join(f"`{k or '(none)'}`: {v}" for k, v in ext.most_common()), "", "```", *tree(root, 3), "```", ""]
    audio = [p for p in files if p.suffix.lower() in AUDIO_EXT]
    if audio:
        sample = random.sample(audio, min(n_sample, len(audio)))
        out.append(f"Sample of {len(sample)} audio files (sample rate, channels, duration):")
        for p in sorted(sample):
            try:
                i = sf.info(str(p))
                out.append(f"- `{p.relative_to(root).as_posix()}`: {i.samplerate} Hz, {i.channels} ch, {i.duration:.2f} s")
            except Exception as e:  # noqa: BLE001
                out.append(f"- `{p.relative_to(root).as_posix()}`: unreadable ({e})")
        out.append("")
    for p in sorted(p for p in files if p.suffix.lower() == ".parquet")[:5]:
        import pyarrow.parquet as pq

        pf = pq.ParquetFile(p)
        out += [f"Parquet `{p.relative_to(root).as_posix()}`: {pf.metadata.num_rows} rows", "```", str(pf.schema_arrow), "```", ""]
    for p in sorted(p for p in files if p.suffix.lower() in {".md", ".csv", ".json", ".txt"})[:6]:
        head = "\n".join(p.read_text(errors="replace").splitlines()[:25])
        out += [f"Head of `{p.relative_to(root).as_posix()}`:", "```", head, "```", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--samples", type=int, default=20)
    ap.add_argument("--config", default=None)
    args = ap.parse_args()
    cfg = load_config(args.config)
    set_seeds(cfg["seed"])
    root = project_path(cfg, "data_raw") / cfg["datasets"]["dads"]["dir"]
    if not root.exists():
        print(f"{root} does not exist. Run: python scripts/download_data.py --only dads")
        return 1
    block = f"{BEGIN}\n\n{inspect(root, args.samples)}\n{END}"
    notes = PROJECT_ROOT / "docs" / "data_notes.md"
    text = notes.read_text(encoding="utf-8")
    if BEGIN in text and END in text:
        text = text[: text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    else:
        text += "\n" + block + "\n"
    notes.write_text(text, encoding="utf-8")
    print(f"updated {notes}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
